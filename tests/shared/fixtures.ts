/**
 * A project from a slicer that isn't converted: the PrusaSlicer fixture with its settings file's first line naming SuperSlicer,
 * made the way the library's own test makes it. SuperSlicer is built on PrusaSlicer and saves the same layout.
 */
export function superSlicerProject(): Buffer {
  const entries = unzipSync(fixture("prusaslicer-2.9.6.3mf"));
  entries["Metadata/Slic3r_PE.config"] = strToU8("; generated by SuperSlicer 2.5.59 on 2024-01-01\n; layer_height = 0.2\n");
  return Buffer.from(zipSync(entries));
}

/**
 * The sample with names a hostile file could carry, hundreds of characters with nowhere to break: filament 1's type and
 * name, and filament 2's name. With Filament set to Snapmaker, filament 2 is renamed, so its "was" is that long; filament
 * 1's type is one no preset has, so it keeps its own name. Filaments 3 and 4 are as the sample has them.
 */
export function longNamesProject(): Buffer {
  const entries = unzipSync(fixture(SAMPLE));
  const settings = JSON.parse(strFromU8(entries["Metadata/project_settings.config"]!)) as { filament_type: string[]; filament_settings_id: string[] };
  settings.filament_type[0] = "T".repeat(300);
  settings.filament_settings_id[0] = "N".repeat(400);
  settings.filament_settings_id[1] = "W".repeat(400);
  entries["Metadata/project_settings.config"] = strToU8(JSON.stringify(settings));
  return Buffer.from(zipSync(entries));
}

/**
 * A project with more filaments than the U1 has toolheads, made from one of the scene fixtures: seventeen filaments
 * (copies of the first), one object on filament 17 on a plate that also prints filament 1, and filament changes at
 * four heights on plate 2. The library's notes about plates' filaments follow: the long one about filament 17, the one
 * about the two filaments of plate 2 that share a toolhead and where to add the pause, and a plain line for plate 1.
 */
export function plateNotesProject(base = SAMPLE, object = "Disc"): Buffer {
  const count = 17;
  const entries = unzipSync(fixture(base));
  const settings = JSON.parse(strFromU8(entries["Metadata/project_settings.config"]!)) as Record<string, unknown> & { filament_colour: string[] };
  const before = settings.filament_colour.length;
  for (const [key, value] of Object.entries(settings)) {
    if (!Array.isArray(value)) continue;
    if (key === "flush_volumes_matrix" && value.length === before * before) settings[key] = Array.from({ length: count * count }, (_, i) => (Math.floor(i / count) === i % count ? "0" : "300"));
    else if (value.length === before) settings[key] = [...value, ...Array.from({ length: count - before }, () => value[0] as unknown)];
    else if (value.length === 2 * before) settings[key] = [...value, ...Array.from({ length: count - before }, () => [value[0], value[1]] as unknown[]).flat()];
  }
  entries["Metadata/project_settings.config"] = strToU8(JSON.stringify(settings));
  const objects = strFromU8(entries["Metadata/model_settings.config"]!);
  const moved = objects.replace(new RegExp(`(<metadata key="name" value="${object}"/>\\s*<metadata key="extruder" value=")\\d+(")`), `$1${count}$2`);
  if (moved === objects) throw new Error(`${base} has no object named ${object}`);
  entries["Metadata/model_settings.config"] = strToU8(moved);
  const changes = [[5, 1], [10, 2], [15, 3], [20, 5]].map(([height, filament]) => `<layer top_z="${height}" type="2" extruder="${filament}" color="#112233" extra="" gcode="tool_change"/>`).join("\n");
  entries["Metadata/custom_gcode_per_layer.xml"] = strToU8(`<?xml version="1.0" encoding="utf-8"?>\n<custom_gcodes_per_layer>\n<plate>\n<plate_info id="2"/>\n${changes}\n<mode value="MultiAsSingle"/>\n</plate>\n</custom_gcodes_per_layer>\n`);
  return Buffer.from(zipSync(entries));
}

/**
 * The Polymaker project with plate 2 changed the way the library's own example test changes it: filament changes to 1,
 * 2, 3 and 5 at 5, 10, 15 and 20 mm, on a plate that prints filament 4, and with `pause`, a pause at 12 mm. Filaments 4
 * and 5 then share a toolhead, and the library's note says how the plate prints: what to load, and where the pause is or
 * goes.
 */
export function sharedToolheadProject({ pause }: { pause: boolean }): Buffer {
  const entries = unzipSync(fixture(POLYMAKER));
  const changes = [[5, 1], [10, 2], [15, 3], [20, 5]].map(([height, filament]) => `<layer top_z="${height}" type="2" extruder="${filament}" color="" extra="" gcode="tool_change"/>`).join("");
  const stop = pause ? `<layer top_z="12" type="1" extruder="1" color="" extra="" gcode="M601"/>` : "";
  entries["Metadata/custom_gcode_per_layer.xml"] = strToU8(`<custom_gcodes_per_layer><plate><plate_info id="2"/>${changes}${stop}<mode value="MultiAsSingle"/></plate></custom_gcodes_per_layer>`);
  return Buffer.from(zipSync(entries));
}

/**
 * The Polymaker project with a height range on one object that sets 0.1 mm layers, the way the library's own layer
 * height test makes it. 0.1 mm is below what the U1's 0.6 mm profiles use and within what its 0.4 mm ones do, so made
 * for 0.6 mm nozzles the library's note about the layers follows, and for 0.4 mm it doesn't.
 */
export function thinLayersProject(): Buffer {
  const entries = unzipSync(fixture(POLYMAKER));
  entries["Metadata/layer_config_ranges.xml"] = strToU8(
    '<?xml version="1.0" encoding="utf-8"?>\n<objects>\n <object id="3">\n  <range min_z="5" max_z="10">\n   <option opt_key="extruder">2</option>\n   <option opt_key="layer_height">0.1</option>\n  </range>\n </object>\n</objects>\n',
  );
  return Buffer.from(zipSync(entries));
}
