/** The test files and the facts both browser suites compare against. */
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { strFromU8, strToU8, unzipSync, zipSync } from "fflate";

const fixtures = fileURLToPath(new URL("../fixtures/", import.meta.url));

export const fixturePath = (name: string) => join(fixtures, name);
export const fixture = (name: string) => readFileSync(fixturePath(name));
export const sha256 = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex");
export const libraryVersion = (JSON.parse(readFileSync(fileURLToPath(new URL("../../node_modules/any2orca/package.json", import.meta.url)), "utf-8")) as { version: string }).version;
export const SAMPLE = "bambu-studio-2.8.4.57-beta.3mf";
/**
 * The PrusaSlicer fixtures: a box, a box with painted fuzzy skin, a four-filament scene, that scene spread over four beds,
 * and the four beds from 2.9.7 with known pauses on some beds only.
 */
export const PRUSA_FIXTURES = ["prusaslicer-2.9.6.3mf", "prusaslicer-2.9.6-fuzzy-skin.3mf", "prusaslicer-2.9.6-scene.3mf", "prusaslicer-2.9.6-beds.3mf", "prusaslicer-2.9.7-beds-pauses.3mf"];

/**
 * A project from a slicer that isn't converted: the PrusaSlicer fixture with its settings file's first line naming SuperSlicer,
 * made the way the library's own test makes it. SuperSlicer is built on PrusaSlicer and saves the same layout.
 */
export function superSlicerProject(): Buffer {
  const entries = unzipSync(fixture("prusaslicer-2.9.6.3mf"));
  entries["Metadata/Slic3r_PE.config"] = strToU8("; generated by SuperSlicer 2.5.59 on 2024-01-01\n; layer_height = 0.2\n");
  return Buffer.from(zipSync(entries));
}

/**
 * The sample with names a hostile file could carry, hundreds of characters with nowhere to break: filament 1's type and
 * name, and filament 2's name. With Filament set to Snapmaker, filament 2 is renamed, so its "was" is that long; filament
 * 1's type is one no preset has, so it keeps its own name. Filaments 3 and 4 are as the sample has them.
 */
export function longNamesProject(): Buffer {
  const entries = unzipSync(fixture(SAMPLE));
  const settings = JSON.parse(strFromU8(entries["Metadata/project_settings.config"]!)) as { filament_type: string[]; filament_settings_id: string[] };
  settings.filament_type[0] = "T".repeat(300);
  settings.filament_settings_id[0] = "N".repeat(400);
  settings.filament_settings_id[1] = "W".repeat(400);
  entries["Metadata/project_settings.config"] = strToU8(JSON.stringify(settings));
  return Buffer.from(zipSync(entries));
}
